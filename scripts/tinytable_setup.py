class SetupError(Exception):
    pass


# --- small helpers -----------------------------------------------------------


def ok(text: str) -> None:
    print(f"  [ok]   {text}")


def missing(text: str) -> None:
    print(f"  [--]   {text}")


def problem(text: str) -> None:
    print(f"  [!!]   {text}")


def owner() -> tuple[int, int]:
    """The repository owner, so generated files stay editable on the host."""

    info = WORK.stat()
    return info.st_uid, info.st_gid


def make_private(path: Path, mode: int, uid_gid: tuple[int, int] | None = None) -> None:
    uid, gid = uid_gid or owner()
    try:
        os.chown(path, uid, gid)
    except OSError:
        pass  # Docker Desktop bind mounts may not support ownership changes.
    try:
        os.chmod(path, mode)
    except OSError:
        pass


def ensure_local() -> None:
    if not WORK.is_dir() or not (WORK / "compose.yaml").is_file():
        raise SetupError("The repository is not mounted at /work. Run this through `docker compose run --rm setup ...`.")
    for directory in (LOCAL, LOCAL / "replika", LOCAL / "kindroid"):
        directory.mkdir(exist_ok=True)
        make_private(directory, 0o700)


def write_private(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8")
    make_private(path, 0o600)


def read_env(path: Path) -> dict[str, str]:
    """Parse the KEY=value files Compose reads with env_file."""

    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
            value = value[1:-1]
        values[key.strip()] = value
    return values


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(WORK))
    except ValueError:
        return str(path)


def ask(prompt: str, default: str | None = None) -> str:
    if not sys.stdin.isatty():
        if default is None:
            raise SetupError(f"{prompt}: no terminal for input; pass it as an option instead.")
        return default
    suffix = f" [{default}]" if default else ""
    answer = input(f"{prompt}{suffix}: ").strip()
    return answer or (default or "")


def fetch(url: str, timeout: float = 3) -> dict:
    with urllib.request.urlopen(url, timeout=timeout) as response:
        return json.loads(response.read() or b"{}")


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# --- commands ----------------------------------------------------------------


def cmd_init(args: argparse.Namespace) -> int:
    ensure_local()
    matrix_env = LOCAL / "matrix.env"
    if matrix_env.is_file():
        print(f"{rel(matrix_env)} already exists; keeping the homeserver name it sets.")
    else:
        print("The Matrix server name becomes part of every user ID (@you:<name>) and cannot be")
        print("changed later without deleting the homeserver data.")
        print("  With Tailscale: tinytable-matrix.<your-tailnet>.ts.net (see docs/SETUP.md)")
        print("  Without:        any name you like, for example tinytable.home")
        name = args.server_name or ask("Matrix server name")
        if not re.fullmatch(r"[A-Za-z0-9.-]+(:[0-9]+)?", name or ""):
            raise SetupError("The server name must be a host name such as tinytable.home.")
        write_private(matrix_env, (
            "# Generated by `setup init`. Changing the server name later requires a new homeserver.\n"
            f"CONTINUWUITY_SERVER_NAME={name}\n"
            f"CONTINUWUITY_REGISTRATION_TOKEN={secrets.token_urlsafe(24)}\n"
        ))
        print(f"Wrote {rel(matrix_env)}.")
    for name, text in (
        ("tinytable.env", TINYTABLE_ENV),
        ("replika.env", REPLIKA_ENV),
        ("kindroid.env", KINDROID_ENV),
        ("tailscale.env", TAILSCALE_ENV),
    ):
        path = LOCAL / name
        if path.exists():
            print(f"{rel(path)} already exists; left unchanged.")
        else:
            write_private(path, text)
            print(f"Wrote {rel(path)}.")
    print("\nNext: start the homeserver with `docker compose up -d matrix`, then run `docker compose run --rm setup matrix`.")
    return 0


SEAT_PROMPTS = [
    ("OPERATOR", "Your display name at the table", "Operator"),
    ("REPLIKA_COMPANION", "Display name for your Replika companion", "Replika companion"),
    ("KINDROID_COMPANION", "Display name for your Kindroid companion", "Kindroid companion"),
]


def cmd_names(args: argparse.Namespace) -> int:
    """Write local/seats.env: the names and pronouns shown for each seat."""

    ensure_local()
    current = read_env(LOCAL / "seats.env")
    # Installations set up before `setup names` existed kept names in bridge.env.
    bridge = read_env(LOCAL / "bridge.env")
    for key, legacy in (("REPLIKA_COMPANION", "TINYTABLE_COMPANION_A_NAME"), ("KINDROID_COMPANION", "TINYTABLE_COMPANION_B_NAME"), ("OPERATOR", "TINYTABLE_OPERATOR_NAME")):
        if bridge.get(legacy) and not current.get(f"TINYTABLE_{key}_NAME"):
            current[f"TINYTABLE_{key}_NAME"] = bridge[legacy]
    print("TinyTable identifies seats by provider (operator, replika-companion, kindroid-companion).")
    print("Choose how each one is shown. Pronouns are used in disclosure lines, e.g. they/them, she/her.")
    lines = ["# Generated by `setup names`; rerun it to change these. Restart with `docker compose up -d` after."]
    given = {"OPERATOR": args.operator_name, "REPLIKA_COMPANION": args.replika_name, "KINDROID_COMPANION": args.kindroid_name}
    for key, prompt, default in SEAT_PROMPTS:
        name = given.get(key) or ask(prompt, current.get(f"TINYTABLE_{key}_NAME") or default)
        pronouns = ask(f"Pronouns for {name}", current.get(f"TINYTABLE_{key}_PRONOUNS") or "they/them")
        if "\n" in name or "\n" in pronouns:
            raise SetupError("Names and pronouns must fit on one line.")
        lines += [f"TINYTABLE_{key}_NAME={name}", f"TINYTABLE_{key}_PRONOUNS={pronouns}"]
    write_private(LOCAL / "seats.env", "\n".join(lines) + "\n")
    print(f"Wrote {rel(LOCAL / 'seats.env')}.")
    return 0


def wait_for_matrix(seconds: int = 60) -> None:
    deadline = time.monotonic() + seconds
    while True:
        try:
            fetch(f"{MATRIX_URL}/_matrix/client/versions")
            return
        except (OSError, ValueError):
            if time.monotonic() > deadline:
                raise SetupError("The homeserver is not answering. Start it with `docker compose up -d matrix` and check `docker compose logs matrix`.")
            time.sleep(2)


def client_url(server_name: str) -> str:
    tailscale = read_env(LOCAL / "tailscale.env")
    if tailscale.get("TS_AUTHKEY") and server_name.endswith(".ts.net"):
        return f"https://{server_name}"
    return "http://127.0.0.1:8008"


def cmd_matrix(args: argparse.Namespace) -> int:
    ensure_local()
    matrix_env = read_env(LOCAL / "matrix.env")
    if not matrix_env.get("CONTINUWUITY_REGISTRATION_TOKEN"):
        raise SetupError("Run `docker compose run --rm setup init` first.")
    bridge_env = LOCAL / "bridge.env"
    if bridge_env.exists():
        raise SetupError(f"{rel(bridge_env)} already exists, so the Matrix accounts were already created. "
                         "See docs/SETUP.md, \"Starting over\", if you need to redo this step.")
    print("Waiting for the homeserver...")
    wait_for_matrix()
    first_token = os.getenv("MATRIX_FIRST_TOKEN", "").strip()
    if not first_token:
        print("\nThe homeserver printed a one-time registration token for its first account. Show it with:")
        print(f"    {COMPOSE} logs matrix | grep 'using the registration token'")
        first_token = ask("Paste that token")
    operator = args.operator_username or ask("Your Matrix username (letters, digits, - or _)", "operator")
    if not (LOCAL / "seats.env").is_file():
        cmd_names(argparse.Namespace(operator_name=None, replika_name=None, kindroid_name=None))
    names = read_env(LOCAL / "seats.env")
    operator_name = names.get("TINYTABLE_OPERATOR_NAME") or "Operator"
    companion_a = names.get("TINYTABLE_REPLIKA_COMPANION_NAME") or "Replika companion"
    companion_b = names.get("TINYTABLE_KINDROID_COMPANION_NAME") or "Kindroid companion"
    print("\nNow choose your own Matrix password (at least 12 characters).")
    command = [
        sys.executable, str(APP / "scripts" / "matrix_bootstrap.py"),
        "--homeserver", MATRIX_URL,
        "--client-url", client_url(matrix_env.get("CONTINUWUITY_SERVER_NAME", "")),
        "--operator-username", operator,
        "--operator-name", operator_name,
        "--companion-a-name", companion_a,
        "--companion-b-name", companion_b,
        "--output-env", str(bridge_env),
        "--digest-env", str(LOCAL / "operator.env"),
    ]
    env = os.environ | {
        "MATRIX_FIRST_TOKEN": first_token,
        "MATRIX_REGISTRATION_TOKEN": matrix_env["CONTINUWUITY_REGISTRATION_TOKEN"],
    }
    result = subprocess.run(command, env=env, check=False)
    for path in (bridge_env, LOCAL / "operator.env"):
        if path.exists():
            make_private(path, 0o600)
    if result.returncode != 0:
        return result.returncode
    print("\nNext: add the Replika and Kindroid credentials (docs/SETUP.md), then run `docker compose run --rm setup secrets`.")
    return 0


def cmd_kindroid_har(args: argparse.Namespace) -> int:
    ensure_local()
    har = (WORK / args.har).resolve()
    if not har.is_file() or WORK not in har.parents:
        raise SetupError(f"No HAR file at {args.har}. Put it inside this folder, for example local/kindroid/kindroid.har.")
    with tempfile.TemporaryDirectory() as temporary:
        result = subprocess.run(
            [sys.executable, str(APP / "tools" / "extract_kindroid_session.py"), str(har), temporary],
            check=False,
        )
        if result.returncode != 0:
            return result.returncode
        target = LOCAL / "kindroid" / "session.json"
        shutil.copyfile(Path(temporary) / "session.json", target)
        make_private(target, 0o600)
    print(f"Wrote {rel(target)}. The HAR file contains login tokens: delete it now that it has been read.")
    print("Next: run `docker compose run --rm setup secrets`.")
    return 0


def check_replika(report) -> bool:
    """Validate the Replika companion's inputs; report(...) is ok/missing/problem."""

    env = read_env(LOCAL / "replika.env")
    good = True
    try:
        headers = json.loads(env.get("REPLIKA_WS_HEADERS_JSON", "{}") or "{}")
    except json.JSONDecodeError:
        problem("local/replika.env: REPLIKA_WS_HEADERS_JSON is not valid JSON (wrap it in single quotes)")
        headers, good = {}, False
    if not isinstance(headers, dict):
        problem("local/replika.env: REPLIKA_WS_HEADERS_JSON must be a JSON object such as '{}'")
        good = False
    absent = [name for name in ("REPLIKA_CHAT_ID", "REPLIKA_CUSTOMER_ID", "REPLIKA_BOT_ID") if not env.get(name)]
    if absent:
        missing("local/replika.env has no " + ", ".join(absent) + " (recommended; copy them from the capture)")
    bootstrap = LOCAL / "replika" / "bootstrap.md"
    if not bootstrap.is_file():
        missing("local/replika/bootstrap.md is missing")
        return False
    sys.path.insert(0, str(APP))
    try:
        from replika_provider import load_bootstrap_file

        frames = load_bootstrap_file(str(bootstrap))
    except Exception as exc:  # the loader raises ValueError and friends with a readable reason
        problem(f"local/replika/bootstrap.md was rejected: {exc}")
        return False
    if not frames:
        problem("local/replika/bootstrap.md contains no client-to-server frames")
        return False
    if good:
        report(f"Replika capture accepted ({len(frames)} start-up frames)")
    return good


def load_kindroid_session() -> dict | None:
    path = LOCAL / "kindroid" / "session.json"
    if not path.is_file():
        missing("local/kindroid/session.json is missing")
        return None
    try:
        session = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        problem("local/kindroid/session.json is not valid JSON")
        return None
    # kindroid:nova-private is the channel name used before seats were renamed.
    if not isinstance(session, dict) or session.get("provider") != "kindroid" or session.get("channel_id") not in {"kindroid:companion", "kindroid:nova-private"}:
        problem("local/kindroid/session.json is not a Kindroid companion (kindroid:companion) session file")
        return None
    absent = [name for name in ("account_id", "ai_id", "speaker_id") if not str(session.get(name) or "").strip()]
    if absent:
        problem("local/kindroid/session.json is missing " + ", ".join(absent))
        return None
    return session


def identity_digests(session: dict) -> dict[str, str]:
    """Match kindroid_provider.session_identity_evidence."""

    def digest(value: object) -> str:
        return hashlib.sha256(str(value).strip().encode("utf-8")).hexdigest()

    return {
        "KINDROID_ACCOUNT_HASH": digest(session["account_id"]),
        "KINDROID_CHANNEL_HASH": digest(session.get("provider_channel_id") or session["ai_id"]),
        "KINDROID_SPEAKER_HASH": digest(session["speaker_id"]),
    }


def install_secret(source: Path, relative: str) -> None:
    target = SECRETS / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    make_private(SECRETS, 0o700, (SERVICE_UID, SERVICE_GID))
    make_private(target.parent, 0o500, (SERVICE_UID, SERVICE_GID))
    temporary = target.with_name(target.name + ".new")
    shutil.copyfile(source, temporary)
    make_private(temporary, 0o400, (SERVICE_UID, SERVICE_GID))
    os.replace(temporary, target)


def cmd_secrets(args: argparse.Namespace) -> int:
    ensure_local()
    if not SECRETS.is_dir():
        raise SetupError("The secrets volume is not mounted at /secrets. Run this through `docker compose run --rm setup secrets`.")
    print("Replika companion:")
    if check_replika(ok):
        install_secret(LOCAL / "replika" / "bootstrap.md", "replika/bootstrap.md")
        ok("bootstrap capture copied into the secrets volume")
    else:
        missing("not imported; the Replika companion stays unavailable until this is fixed")
    print("Kindroid companion:")
    session = load_kindroid_session()
    if session is not None:
        install_secret(LOCAL / "kindroid" / "session.json", "kindroid/session.json")
        lines = "".join(f"{key}={value}\n" for key, value in identity_digests(session).items())
        write_private(LOCAL / "identity.env", "# Generated by `setup secrets` from local/kindroid/session.json.\n" + lines)
        ok("session file copied into the secrets volume; identity digests written to local/identity.env")
        if not read_env(LOCAL / "kindroid.env").get("KINDROID_API_KEY"):
            missing("local/kindroid.env has no KINDROID_API_KEY: the Kindroid companion will use the browser session, which expires after an hour")
    else:
        missing("not imported; the Kindroid companion stays unavailable until this is fixed")
    print(f"\nRestart the stack to pick up changes: {COMPOSE} up -d --force-recreate")
    return 0


def cmd_check(args: argparse.Namespace) -> int:
    ensure_local()
    required_ok = True
    print("Configuration (./local):")
    matrix_env = read_env(LOCAL / "matrix.env")
    if matrix_env.get("CONTINUWUITY_SERVER_NAME") and matrix_env.get("CONTINUWUITY_REGISTRATION_TOKEN"):
        ok(f"homeserver name: {matrix_env['CONTINUWUITY_SERVER_NAME']}")
    else:
        missing("local/matrix.env: run `setup init`")
        required_ok = False
    names = read_env(LOCAL / "seats.env")
    if names:
        ok("names: " + ", ".join(names[key] for key in ("TINYTABLE_OPERATOR_NAME", "TINYTABLE_REPLIKA_COMPANION_NAME", "TINYTABLE_KINDROID_COMPANION_NAME") if names.get(key)))
    else:
        missing("local/seats.env: run `setup names` (until then: Operator, Replika companion, Kindroid companion)")
    if (LOCAL / "tinytable.env").is_file():
        ok("local/tinytable.env present")
    else:
        missing("local/tinytable.env: run `setup init`")
        required_ok = False
    bridge = read_env(LOCAL / "bridge.env")
    digests = read_env(LOCAL / "operator.env")
    if bridge.get("TINYTABLE_OPERATOR_TOKEN") and bridge.get("MATRIX_ROOM_ID"):
        expected = hashlib.sha256(bridge["TINYTABLE_OPERATOR_TOKEN"].encode()).hexdigest()
        if digests.get("TINYTABLE_OPERATOR_TOKEN_SHA256") == expected:
            ok(f"Matrix room {bridge['MATRIX_ROOM_ID']} for {bridge.get('MATRIX_OPERATOR_ID', '?')}")
        else:
            problem("local/operator.env does not match the token in local/bridge.env")
            required_ok = False
    else:
        missing("local/bridge.env: run `setup matrix`")
        required_ok = False

    print("Replika companion:")
    replika_ready = False
    installed = SECRETS / "replika" / "bootstrap.md"
    if check_replika(ok):
        if not installed.is_file():
            missing("not imported yet: run `setup secrets`")
        elif sha256_file(installed) != sha256_file(LOCAL / "replika" / "bootstrap.md"):
            missing("local/replika/bootstrap.md changed since it was imported: run `setup secrets`")
        else:
            ok("imported into the secrets volume")
            replika_ready = True

    print("Kindroid companion:")
    kindroid_ready = False
    session = load_kindroid_session()
    if session is not None:
        ok("local/kindroid/session.json looks complete")
        installed = SECRETS / "kindroid" / "session.json"
        identity = read_env(LOCAL / "identity.env")
        if not installed.is_file() or sha256_file(installed) != sha256_file(LOCAL / "kindroid" / "session.json"):
            missing("not imported (or changed since): run `setup secrets`")
        elif identity != identity_digests(session):
            missing("local/identity.env is out of date: run `setup secrets`")
        else:
            ok("imported into the secrets volume")
            kindroid_ready = True
        if read_env(LOCAL / "kindroid.env").get("KINDROID_API_KEY", "").startswith("kn_"):
            ok("API key set (the Kindroid connection does not expire hourly)")
        else:
            missing("no kn_ API key in local/kindroid.env: the browser session expires after an hour")

    print("Remote access:")
    tailscale = read_env(LOCAL / "tailscale.env")
    if tailscale.get("TS_AUTHKEY"):
        ok(f"Tailscale key set; start it with `{COMPOSE} --profile tailscale up -d`")
    else:
        missing("no Tailscale key: Matrix is reachable only at http://127.0.0.1:8008 on this machine")

    print("Running services:")
    try:
        fetch(f"{MATRIX_URL}/_matrix/client/versions")
        ok("homeserver answering")
    except (OSError, ValueError):
        missing(f"homeserver not running ({COMPOSE} up -d)")
    try:
        fetch(f"{TINYTABLE_URL}/health")
        runtime = fetch(f"{TINYTABLE_URL}/runtime")
        ok(f"TinyTable answering (mode {runtime.get('mode', '?')})")
    except (OSError, ValueError):
        missing(f"TinyTable not running ({COMPOSE} up -d)")
    try:
        status = fetch(f"{SIDECAR_URL}/status")
        state = status.get("state") or status.get("status") or "unknown"
        (ok if state == "connected" else missing)(f"Kindroid sidecar state: {state}")
    except (OSError, ValueError):
        missing("Kindroid sidecar not answering")

    print()
    if not required_ok:
        print("Not ready yet: fix the [--] / [!!] items above (docs/SETUP.md explains each).")
        return 1
    if replika_ready and kindroid_ready:
        print(f"Ready: Matrix and both companions are configured. Start or update everything with: {COMPOSE} up -d")
        return 0
    absent = " and ".join(name for name, ready in (("the Replika companion", replika_ready), ("the Kindroid companion", kindroid_ready)) if not ready)
    print(f"Matrix is ready, but {absent} {'is' if ' and ' not in absent else 'are'} not configured yet "
          "(docs/SETUP.md steps 6 to 8). The table works without them, but they will not answer.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)

    init = commands.add_parser("init", help="create ./local with generated settings and credential templates")
    init.add_argument("--server-name", help="Matrix server name, e.g. tinytable.home")
    init.set_defaults(run=cmd_init)

    names = commands.add_parser("names", help="choose the names and pronouns shown for you and each companion")
    names.add_argument("--operator-name")
    names.add_argument("--replika-name")
    names.add_argument("--kindroid-name")
    names.set_defaults(run=cmd_names)

    matrix = commands.add_parser("matrix", help="create your Matrix account, the bot accounts, and the private room")
    matrix.add_argument("--operator-username")
    matrix.set_defaults(run=cmd_matrix)

    har = commands.add_parser("kindroid-har", help="make local/kindroid/session.json from a Kindroid browser HAR file")
    har.add_argument("har", help="path inside this folder, e.g. local/kindroid/kindroid.har")
    har.set_defaults(run=cmd_kindroid_har)

    imports = commands.add_parser("secrets", help="validate the companion credentials and copy them into the secrets volume")
    imports.set_defaults(run=cmd_secrets)

    check = commands.add_parser("check", help="report what is configured and running")
    check.set_defaults(run=cmd_check)

    args = parser.parse_args()
    try:
        return args.run(args)
    except SetupError as exc:
        print(f"\nSetup stopped: {exc}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("\nCancelled.", file=sys.stderr)
        return 130


if __name__ == "__main__":
    sys.exit(main())
